def _bigrams(s: str) -> set[str]:
    s = re.sub(r"\s+", "", (s or "").lower())
    if len(s) <= 1:
        return {s} if s else set()
    return {s[i:i + 2] for i in range(len(s) - 1)}


def search(query: str, *, top_k: int = 3) -> list[dict]:
    """关键词 + 字符 bigram 重合度打分，返回 top_k 条（含分数，供低置信判断）。"""
    q = (query or "").strip()
    if not q:
        return []
    q_bg = _bigrams(q)
    scored: list[tuple[float, tuple]] = []
    for entry in KB_ENTRIES:
        _id, title, keywords, body = entry
        score = 0.0
        # 关键词命中（权重最高，人工策展的判据）
        for kw in keywords:
            if kw and kw in q:
                score += 3.0
        # 标题子串
        if title.split("：")[-1] in q or any(t and t in q for t in title.split("：")):
            score += 1.5
        # bigram 重合度（Jaccard 近似，兜长尾问法）
        e_bg = _bigrams(title + " " + " ".join(keywords))
        if q_bg and e_bg:
            score += 2.0 * len(q_bg & e_bg) / len(q_bg | e_bg)
        if score > 0:
            scored.append((score, entry))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [{"id": e[0], "title": e[1], "body": e[3], "score": round(s, 2)}
            for s, e in scored[:top_k]]